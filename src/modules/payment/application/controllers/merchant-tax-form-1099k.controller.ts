import { Controller, Get, Param, Query, UseGuards, Req, NotFoundException, BadRequestException } from '@nestjs/common';
import { ApiTags, ApiOperation, ApiBearerAuth, ApiResponse } from '@nestjs/swagger';
import { JwtAuthGuard } from '../../../../shared/guards/jwt-auth.guard';
import { RolesGuard } from '../../../../shared/guards/roles.guard';
import { Roles, UserRole } from '../../../../shared/decorators/roles.decorator';
import { MerchantTaxFormPort } from '../../ports/outbound/merchant-tax-form.port';
import { MerchantTaxForm1099KResponseDto, toMerchantTaxForm1099KResponseDto } from '../dto/merchant-tax-form-1099k.dto';

/**
 * Merchant 1099-K Controller
 * Where a merchant furnishes/views their own copy — see
 * `TaxForm1099KService`/`MerchantTaxForm1099K`'s own docblocks for why
 * this is a computed, illustrative figure rather than something this
 * platform ever actually files with the IRS. Read-only: forms are
 * generated by the annual sweep or an operator's on-demand trigger
 * (see `MerchantTaxForm1099KAdminController`), never created here.
 */
@ApiTags('Merchant 1099-K Tax Forms')
@ApiBearerAuth()
@Controller('tax-forms/1099k')
@UseGuards(JwtAuthGuard, RolesGuard)
@Roles(UserRole.MERCHANT, UserRole.ADMIN, UserRole.READONLY)
export class MerchantTaxForm1099KController {
  constructor(private readonly taxFormPort: MerchantTaxFormPort) {}

  @Get()
  @ApiOperation({ summary: "List this merchant's own 1099-K forms, most recent tax year first" })
  @ApiResponse({ status: 200, type: [MerchantTaxForm1099KResponseDto] })
  async list(@Req() req: any, @Query('limit') limit?: string): Promise<MerchantTaxForm1099KResponseDto[]> {
    const merchantId = req.user?.merchantId;
    const forms = await this.taxFormPort.findByMerchantId(merchantId, { limit: limit ? Number(limit) : undefined });
    return forms.map(toMerchantTaxForm1099KResponseDto);
  }

  @Get(':taxYear')
  @ApiOperation({ summary: 'Get this own 1099-K form for a specific tax year' })
  @ApiResponse({ status: 200, type: MerchantTaxForm1099KResponseDto })
  @ApiResponse({ status: 400, description: 'taxYear must be a 4-digit year' })
  @ApiResponse({ status: 404, description: 'No form generated for this tax year' })
  async getByYear(@Param('taxYear') taxYearParam: string, @Req() req: any): Promise<MerchantTaxForm1099KResponseDto> {
    const taxYear = Number(taxYearParam);
    if (!Number.isInteger(taxYear) || taxYear < 2000 || taxYear > 2100) {
      throw new BadRequestException({ statusCode: 400, error: 'taxYear must be a 4-digit year', code: 'INVALID_TAX_YEAR' });
    }
    const merchantId = req.user?.merchantId;
    const form = await this.taxFormPort.findByMerchantAndYear(merchantId, taxYear);
    if (!form) {
      throw new NotFoundException({
        statusCode: 404,
        error: `No 1099-K form found for tax year ${taxYear}`,
        code: 'TAX_FORM_NOT_FOUND',
      });
    }
    return toMerchantTaxForm1099KResponseDto(form);
  }
}
