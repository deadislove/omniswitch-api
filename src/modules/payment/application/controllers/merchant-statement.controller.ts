import { Controller, Get, Param, Query, UseGuards, Req, NotFoundException, ForbiddenException } from '@nestjs/common';
import { ApiTags, ApiOperation, ApiBearerAuth, ApiResponse } from '@nestjs/swagger';
import { JwtAuthGuard } from '../../../../shared/guards/jwt-auth.guard';
import { RolesGuard } from '../../../../shared/guards/roles.guard';
import { Roles, UserRole } from '../../../../shared/decorators/roles.decorator';
import { MerchantStatementPort } from '../../ports/outbound/merchant-statement.port';
import { MerchantStatement } from '../../domain/aggregates/merchant-statement.aggregate';
import { MerchantStatementResponseDto, toMerchantStatementResponseDto } from '../dto/merchant-statement.dto';

const toResponse = toMerchantStatementResponseDto;

/**
 * Merchant Statement Controller
 * A merchant's own periodic statements — see
 * `MerchantStatementService`/`MerchantStatement`'s own docblocks for how
 * each one is computed. Read-only: statements are generated by the
 * monthly sweep or an operator's on-demand trigger (see
 * `MerchantStatementAdminController`), never created through this
 * controller.
 */
@ApiTags('Merchant Statements')
@ApiBearerAuth()
@Controller('statements')
@UseGuards(JwtAuthGuard, RolesGuard)
export class MerchantStatementController {
  constructor(private readonly statementPort: MerchantStatementPort) {}

  private assertOwnership(statement: MerchantStatement, req: any): void {
    if (req.user?.roles?.includes(UserRole.MERCHANT) && statement.merchantId !== req.user.merchantId) {
      throw new ForbiddenException({ statusCode: 403, error: 'Forbidden', code: 'ACCESS_DENIED' });
    }
  }

  @Get()
  @Roles(UserRole.MERCHANT, UserRole.ADMIN, UserRole.READONLY)
  @ApiOperation({ summary: "List this merchant's own statements, most recent period first" })
  @ApiResponse({ status: 200, type: [MerchantStatementResponseDto] })
  async list(@Req() req: any, @Query('limit') limit?: string): Promise<MerchantStatementResponseDto[]> {
    const merchantId = req.user?.merchantId;
    const statements = await this.statementPort.findByMerchantId(merchantId, {
      limit: limit ? Number(limit) : undefined,
    });
    return statements.map(toResponse);
  }

  @Get(':id')
  @Roles(UserRole.MERCHANT, UserRole.ADMIN, UserRole.READONLY)
  @ApiOperation({ summary: 'Get a single statement by id' })
  @ApiResponse({ status: 200, type: MerchantStatementResponseDto })
  @ApiResponse({ status: 404, description: 'Statement not found' })
  async getById(@Param('id') id: string, @Req() req: any): Promise<MerchantStatementResponseDto> {
    const statement = await this.statementPort.findById(id);
    if (!statement) {
      throw new NotFoundException({ statusCode: 404, error: `Statement ${id} not found`, code: 'STATEMENT_NOT_FOUND' });
    }
    this.assertOwnership(statement, req);
    return toResponse(statement);
  }
}
